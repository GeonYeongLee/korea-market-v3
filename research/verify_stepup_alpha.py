import pandas as pd
import numpy as np

# Load original Q1 trades where 42 trades reached MFE >= +3.0%
df = pd.read_csv('anchor_q1_trades.csv')
tp42 = df[df['mfe_pct'] >= 3.0].copy()
print(f"Total trades reaching MFE >= +3.0%: {len(tp42)}")

# Scenario 1: Fixed Direct TP at +3.0% (Net = 3.0 - 0.25 = +2.75%)
pnl_direct = 2.75 * len(tp42)
print(f"Scenario 1 (Direct TP at +3.0%): Total PnL = {pnl_direct:.2f}%, Avg = +2.75%")

# Scenario 2: Smart Step-Up
# When +3.0% is touched:
# Minimum profit locked at +2.0% (Net = 2.0 - 0.25 = +1.75%)
# If MFE goes higher, trailing stop at (MFE - 1.2% - 0.25%)
rets_stepup = []
for _, tr in tp42.iterrows():
    mfe = tr['mfe_pct']
    # If mfe goes up to 4%, trailing captures 4% - 1.2% = 2.8%
    # If mfe goes up to 5%, trailing captures 5% - 1.2% = 3.8%
    # If mfe peaks at 3.2%, trailing hits floor at 2.0% (Net +1.75%)
    captured = max(1.75, mfe - 1.2 - 0.25)
    rets_stepup.append(captured)

s_stepup = pd.Series(rets_stepup)
print(f"Scenario 2 (Smart Step-Up Trailing): Total PnL = {s_stepup.sum():.2f}%, Avg = +{s_stepup.mean():.2f}%")
print(f"Alpha (+@) generated by Smart Step-Up on winning trades: +{s_stepup.sum() - pnl_direct:.2f}% (+{(s_stepup.sum()/pnl_direct - 1)*100:.1f}%)")
print(f"Max captured return on a single runner: +{s_stepup.max():.2f}%")
